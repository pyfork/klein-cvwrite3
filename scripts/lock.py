"""Writes requirements.lock: every package sk24 installs (the indirect ones too), each with its sha256
hashes, for Linux x86_64 and Python 3.10. Plain pip and the standard library, no lock tool (senior S7).

    python3 scripts/lock.py          after any change to requirements.txt; commit both files

How: pip downloads the Linux wheels into a temp folder (this resolves the full set), then PyPI's JSON
lists the sha256 of every file of each pinned version. Every downloaded wheel's own hash must be in
that list, or the script stops. sk24 installs with `pip install --require-hashes --only-binary :all:`.
"""
import hashlib
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLATFORMS = ["manylinux_2_35_x86_64", "manylinux_2_34_x86_64", "manylinux_2_28_x86_64",
             "manylinux_2_17_x86_64", "manylinux2014_x86_64", "manylinux_2_5_x86_64",
             "manylinux1_x86_64", "linux_x86_64", "any"]
# Ubuntu 22.04 on sk24: glibc 2.35, Python 3.10.12.
WHEEL = re.compile(r"^(?P<name>[^-]+)-(?P<version>[^-]+)-")


def normalise(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def download(folder):
    cmd = [sys.executable, "-m", "pip", "download", "-q", "-r", str(ROOT / "requirements.txt"), "-d", folder,
           "--python-version", "3.10", "--implementation", "cp", "--abi", "cp310", "--abi", "abi3",
           "--abi", "none", "--only-binary", ":all:"]
    for p in PLATFORMS:
        cmd += ["--platform", p]
    subprocess.run(cmd, check=True)


def pypi_hashes(name, version):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        files = json.load(r)["urls"]
    return sorted(f["digests"]["sha256"] for f in files)


def main():
    lines = ["# Generated by scripts/lock.py from requirements.txt. Do not edit by hand.",
             "# Linux x86_64, Python 3.10 (sk24). Install: pip install --require-hashes --only-binary :all: -r requirements.lock",
             ""]
    with tempfile.TemporaryDirectory() as folder:
        download(folder)
        for wheel in sorted(Path(folder).glob("*.whl"), key=lambda p: normalise(p.name)):
            m = WHEEL.match(wheel.name)
            name, version = normalise(m["name"]), m["version"]
            local = hashlib.sha256(wheel.read_bytes()).hexdigest()
            hashes = pypi_hashes(name, version)
            if local not in hashes:
                sys.exit(f"{wheel.name}: downloaded hash not listed by PyPI, stopping")
            lines.append(f"{name}=={version} \\")
            lines += [f"    --hash=sha256:{h} \\" for h in hashes]
            lines[-1] = lines[-1][:-2]
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n")
    print(f"requirements.lock: {sum(1 for l in lines if '==' in l)} packages")


if __name__ == "__main__":
    main()
